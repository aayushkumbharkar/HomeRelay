import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { testDatabase } from '../helpers/database.js';
import { startProcess } from '../helpers/processes.js';
import { event } from '../helpers/fixtures.js';
test('workspace exposes persisted home and audit through MCP, including an unlock denial', async t => {
 const db = await testDatabase(); t.after(() => db.close());
 const token = randomBytes(32).toString('hex');
 const mcp = await startProcess('dist/src/mcp-server.js', { DATABASE_URL: db.url, MCP_TOKEN: token, MCP_PORT: '0' });
 const web = await startProcess('dist/src/web.js', { MCP_TOKEN: token, MCP_URL: `${mcp.url}/mcp`, WEB_PORT: '0' });
 t.after(async () => { await web.stop(); await mcp.stop(); });
 const get = async (path: string) => { const r = await fetch(web.url + path); assert.equal(r.status,200); return r.json(); };
 const home = await get('/api/home');
 assert.deepEqual(home.devices, [{deviceId:'front-door',state:'locked'},{deviceId:'porch-light',state:'off'}]);
 assert.deepEqual(await get('/api/history'), []);
 const csrf = (await get('/api/session')).csrfToken;
 const post = async (path: string, value: unknown) => { const r = await fetch(web.url+path,{method:'POST',headers:{Origin:web.url,'X-CSRF-Token':csrf,'Content-Type':'application/json'},body:JSON.stringify(value)}); assert.equal(r.status,200); return r.json(); };
 const draft = await get('/api/routines/r1');
 await post('/api/approve',{routineRevisionId:'r1',contentHash:draft.contentHash});
 const outcome = await post('/api/events',event);
 const denied = await post('/api/events',{...event,eventId:'unlock-ui',routineRevisionId:'door-denial-r1'});
 assert.equal(denied.decision.actions[0].reasonCode,'DOOR_UNLOCK_FORBIDDEN');
 assert.equal(denied.decision.actions[0].actionId,null);
 const history = await get('/api/history');
 assert.equal(history.length,2); assert.ok(history.some((d: any)=>d.decisionId===outcome.decision.decisionId));
 assert.deepEqual((await get('/api/home')).devices,[{deviceId:'front-door',state:'locked'},{deviceId:'porch-light',state:'on'}]);
 assert.equal((await db.pool.query('SELECT * FROM actions')).rowCount,1);
 assert.match(await (await fetch(web.url)).text(),/HomeRelay/);
});
