import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { randomBytes } from 'node:crypto';
import { testDatabase } from '../helpers/database.js';
import { startProcess } from '../helpers/processes.js';
test('browser approval, execution, denial, replay, refresh, mobile and MCP outage', async t => {
 const db=await testDatabase(); t.after(()=>db.close());
 const token=randomBytes(32).toString('hex');
 let mcp=await startProcess('dist/src/mcp-server.js',{DATABASE_URL:db.url,MCP_TOKEN:token,MCP_PORT:'0'});
 const web=await startProcess('dist/src/web.js',{MCP_URL:mcp.url+'/mcp',MCP_TOKEN:token,WEB_PORT:'0'});
 t.after(async()=>{await web.stop();await mcp.stop();});
 const browser=await chromium.launch({channel:'msedge'});t.after(()=>browser.close());
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.goto(web.url);
 await page.keyboard.press('Tab');
 await expect(page.getByRole('link',{name:'Skip to workspace'})).toBeFocused();
 await expect(page.getByRole('heading',{name:'A light on. A door still locked.'})).toBeVisible();
 await expect(page.locator('#scenario-state')).toHaveText('No scenario run this visit');
 const mainAction=await page.getByRole('button',{name:'Run arrival scenario',exact:true}).boundingBox();
 assert.ok(mainAction && mainAction.y+mainAction.height <= 1000);
 await expect(page.getByRole('button',{name:'Approve routine',exact:true})).toBeEnabled();
 await expect(page.getByRole('button',{name:'Run arrival scenario',exact:true})).toBeDisabled();
 assert.equal((await db.pool.query('SELECT * FROM approvals')).rowCount,0);
 await expect(page.locator('#history')).toContainText('No decisions yet');
 await page.screenshot({path:'test-results/draft.png',fullPage:true});
 await page.getByRole('button',{name:'Approve routine',exact:true}).click();
 await expect(page.getByRole('button',{name:'Run arrival scenario',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Run arrival scenario',exact:true}).click();
 await expect(page.locator('#porch-state')).toHaveText('On');
 await expect(page.locator('#door-state')).toHaveText('Locked');
 await expect(page.locator('#scenario-state')).toHaveText('Executed · porch light on');
 await page.getByRole('button',{name:'Why did this happen?',exact:true}).click();
 await expect(page.locator('#notice')).toContainText('original persisted decision');
 await page.getByRole('button',{name:'Try prohibited action',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('button',{name:'Try prohibited action',exact:true})).toBeFocused();
 await page.getByRole('button',{name:'Try prohibited action',exact:true}).click();
 await page.getByRole('button',{name:'Approve and test denial',exact:true}).click();
 await expect(page.locator('#notice')).toContainText('Denied');
 await page.getByRole('button',{name:'Replay same event',exact:true}).click();
 await expect(page.locator('#notice')).toContainText('No duplicate action');
 assert.equal((await db.pool.query('SELECT * FROM actions')).rowCount,1);
 await page.reload();
 await expect(page.locator('#scenario-state')).toHaveText('No scenario run this visit');
 await expect(page.locator('#history button')).toHaveCount(2);
 await page.locator('#history button').last().click();
 await expect(page.locator('#evidence')).toContainText('ARRIVAL_RULE_MATCHED');
 await expect(page.getByText('Technical evidence',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'test-results/mobile.png',fullPage:true});
 await mcp.stop();await page.getByRole('button',{name:'Refresh evidence',exact:true}).click();
 await expect(page.locator('#notice')).toContainText('unavailable');
 await expect(page.getByRole('button',{name:'Run arrival scenario',exact:true})).toBeDisabled();
 await page.screenshot({path:'test-results/outage.png',fullPage:true});
 mcp=await startProcess('dist/src/mcp-server.js',{DATABASE_URL:db.url,MCP_TOKEN:token,MCP_PORT:String(mcp.port)});
 await page.getByRole('button',{name:'Refresh evidence',exact:true}).click();
 await expect(page.getByRole('button',{name:'Run arrival scenario',exact:true})).toBeEnabled();
 await expect(page.locator('#connection')).toContainText('MCP connected');
 assert.equal((await db.pool.query('SELECT * FROM actions')).rowCount,1);
 assert.deepEqual(errors,[]);
});
